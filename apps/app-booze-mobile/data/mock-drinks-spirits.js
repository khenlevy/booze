/**
 * Spirits aisle — category must match SPIRIT_CATEGORIES in drink-catalog-mock.
 * @param {string} category
 * @param {Omit<Parameters<typeof defineCatalogDrink>[0], 'category'>} p
 */
function spirit(category, p) {
  return defineCatalogDrink({
    category,
    subcategory: category,
    origin: { country: 'Various', region: '' },
    sensory: { body: 'medium', sweetness: 'neutral', intensity: 'high' },
    pairingHints: [],
    occasionTags: ['cocktails'],
    ...p,
  });
}

